export function createUiLanguage(document, initial = "en") {
  let language = initial === "zh-Hans" ? initial : "en";
  const records = new Set(), byNode = new WeakMap();
  function t(value) {
    if (language === "en" || typeof value !== "string") return value;
    if (Object.hasOwn(zh, value)) return zh[value];
    if (Object.hasOwn(zh, value.trim())) return value.replace(value.trim(), zh[value.trim()]);
    let result = value;
    for (const [pattern, replacement] of rules) if (pattern.test(value)) { result = value.replace(pattern, replacement); break; }
    for (const prefix of ["Not saved: ", "Not imported: ", "Revisions unavailable: "]) {
      if (value.startsWith(prefix) && Object.hasOwn(zh, value.slice(prefix.length))) {
        result = t(prefix + "DETAIL").replace("DETAIL", zh[value.slice(prefix.length)]);
      }
    }
    result = result.replace(/\b([\d,]+) (revised fields?|stories|story|cards?|items?|chapters?|lines?|terms?|expressions?)\b/g, (_, n, unit) => `${n} ${units[unit]}`)
      .replace(/ · Auto$/, " · 自动").replace(/ viewed$/, " 已阅读")
      .replace(/ · (Interactive · Game only|Story|Video|Open)$/, (_, kind) => ` · ${zh[kind]}`)
      .replace(/^(Story folder|Game cache|Date scene folder|Backgrounds \/ portraits): /, (_, label) => `${zh[label]}：`)
      .replace(/(\d+) inactive in this story \(original text changed\)/, "$1 项暂不生效（日文原文已变化）");
    return result;
  }
  function bind(node, property, original) {
    let record = byNode.get(node);
    if (!record) { record = { ref: new WeakRef(node), values: new Map() }; byNode.set(node, record); records.add(record); }
    record.values.set(property, original);
    if (property.startsWith("@")) setAttribute(node, property.slice(1), t(original));
    else node[property] = t(original);
  }
  function setAttribute(node, name, value) {
    node.setAttribute(name, value);
    if (name === "title" || name === "placeholder") node[name] = value;
  }
  function initStatic() {
    if (!document.createTreeWalker) return; // Headless unit DOM has no static text.
    const walker = document.createTreeWalker(document.body, 4);
    while (walker.nextNode()) {
      const node = walker.currentNode, original = node.nodeValue, key = original.trim();
      if (Object.hasOwn(zh, key)) bind(node, "nodeValue", original);
    }
    for (const node of document.querySelectorAll("[title], [aria-label], [placeholder]")) {
      for (const attribute of ["title", "aria-label", "placeholder"]) {
        const original = node.getAttribute(attribute);
        if (original && Object.hasOwn(zh, original)) bind(node, "@" + attribute, original);
      }
    }
  }
  function setLanguage(next) {
    language = next === "zh-Hans" ? next : "en";
    document.documentElement.lang = language;
    for (const record of records) {
      const node = record.ref.deref();
      if (!node) { records.delete(record); continue; }
      for (const [property, original] of record.values) {
        if (property.startsWith("@")) setAttribute(node, property.slice(1), t(original));
        else node[property] = t(original);
      }
    }
  }
  return { t, text: (node, value) => bind(node, "textContent", value),
    plain(node, value) { byNode.get(node)?.values.delete("textContent"); node.textContent = value; },
    attr: (node, name, value) => bind(node, "@" + name, value), initStatic, setLanguage, get language() { return language; } };
}
